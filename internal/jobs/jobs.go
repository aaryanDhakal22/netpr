// Package jobs turns uploads into print jobs: stage and convert, plan, send
// over IPP one at a time, then follow the job until the printer finishes it.
package jobs

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"os"
	"path/filepath"
	"time"

	"github.com/aaryanDhakal22/netpr/internal/convert"
	"github.com/aaryanDhakal22/netpr/internal/metrics"
	"github.com/aaryanDhakal22/netpr/internal/notify"
	"github.com/aaryanDhakal22/netpr/internal/pagerange"
	"github.com/aaryanDhakal22/netpr/internal/printer"
	"github.com/aaryanDhakal22/netpr/internal/raster"
	"github.com/aaryanDhakal22/netpr/internal/staging"
	"github.com/aaryanDhakal22/netpr/internal/store"
)

// Source feeds jobs from outside the web UI (e.g. a future email poller).
type Source interface {
	Run(ctx context.Context, svc *Service) error
}

type Service struct {
	Store     *store.Store
	Staging   *staging.Store
	Converter *convert.Gotenberg
	Printer   *printer.Active
	Monitor   *printer.Monitor
	Notifier  notify.Notifier
	Metrics   *metrics.Metrics
	Log       *slog.Logger

	MaxUploadBytes int64
	DryRun         bool
	PollInterval   time.Duration // job status polling; defaults to 3s
	PollTimeout    time.Duration // give up following a job; defaults to 30m

	queue chan task
}

type task struct {
	job  store.Job
	item *staging.Item
}

// Stage stores an upload, converts it to PDF and counts its pages.
func (s *Service) Stage(ctx context.Context, filename string, r io.Reader) (*staging.Item, error) {
	it, err := s.Staging.Create(filename, r, s.MaxUploadBytes)
	if err != nil {
		return nil, err
	}
	if err := s.prepare(ctx, it); err != nil {
		s.Staging.Discard(it)
		return nil, err
	}
	s.Staging.Add(it)
	return it, nil
}

func (s *Service) prepare(ctx context.Context, it *staging.Item) error {
	f, err := convert.Detect(it.OriginalPath(), it.Filename)
	if errors.Is(err, convert.ErrUnsupported) {
		return errors.New("unsupported file type: send a PDF, JPG, PNG, Office document or plain text")
	}
	if err != nil {
		return err
	}
	it.Kind = string(f.Kind)

	start := time.Now()
	err = s.Converter.ToPDF(ctx, it.OriginalPath(), f, it.PDFPath())
	if f.Kind != convert.KindPDF {
		s.Metrics.Converted(time.Since(start), err)
	}
	if err != nil {
		s.Log.Error("convert", "file", it.Filename, "kind", f.Kind, "err", err)
		return errors.New("could not convert this file to PDF")
	}
	os.Remove(it.OriginalPath()) // only the PDF is needed from here on

	if it.Pages, err = s.Converter.PageCount(ctx, it.PDFPath()); err != nil {
		s.Log.Error("page count", "file", it.Filename, "err", err)
		return errors.New("could not read this PDF; it may be damaged or encrypted")
	}
	return nil
}

type Options struct {
	Copies    int
	Duplex    bool
	PageRange string // only valid for a single file
}

type PlannedItem struct {
	Item      *staging.Item
	PageRange string // canonical; "" means all pages
	Pages     int
	Sheets    int
}

type Plan struct {
	Items  []PlannedItem
	Pages  int
	Sheets int
}

// Plan validates a print request against staged items without taking them.
func (s *Service) Plan(ids []string, o Options) (Plan, error) {
	if len(ids) == 0 {
		return Plan{}, errors.New("nothing to print")
	}
	if o.Copies < 1 || o.Copies > 99 {
		return Plan{}, errors.New("copies must be between 1 and 99")
	}
	if o.PageRange != "" && len(ids) > 1 {
		return Plan{}, errors.New("page ranges can only be used when printing a single file")
	}
	var p Plan
	for _, id := range ids {
		it, ok := s.Staging.Get(id)
		if !ok {
			return Plan{}, errors.New("a file expired or was already printed; upload it again")
		}
		canon, pages, err := pagerange.Parse(o.PageRange, it.Pages)
		if err != nil {
			return Plan{}, err
		}
		sheets := pagerange.Sheets(pages, o.Copies, o.Duplex)
		p.Items = append(p.Items, PlannedItem{Item: it, PageRange: canon, Pages: pages, Sheets: sheets})
		p.Pages += pages * o.Copies
		p.Sheets += sheets
	}
	return p, nil
}

// SubmitPDF queues a PDF generated by netpr itself, such as the test page.
// It skips conversion, so it works even when Gotenberg is down.
func (s *Service) SubmitPDF(ctx context.Context, user, filename string, pdf []byte, pages int, o Options) ([]store.Job, error) {
	it, err := s.Staging.Create(filename, bytes.NewReader(pdf), int64(len(pdf)))
	if err != nil {
		return nil, err
	}
	if err := os.Rename(it.OriginalPath(), it.PDFPath()); err != nil {
		s.Staging.Discard(it)
		return nil, err
	}
	it.Kind, it.Pages = string(convert.KindPDF), pages
	s.Staging.Add(it)
	p, err := s.Plan([]string{it.ID}, o)
	if err != nil {
		s.Staging.Remove(it.ID)
		return nil, err
	}
	return s.Submit(ctx, user, p, o)
}

// Submit records and queues each planned item. Items are taken from staging
// first so a double-submitted form cannot print twice.
func (s *Service) Submit(ctx context.Context, user string, p Plan, o Options) ([]store.Job, error) {
	var jobs []store.Job
	for _, pi := range p.Items {
		it, ok := s.Staging.Take(pi.Item.ID)
		if !ok {
			continue
		}
		j := store.Job{
			User: user, Filename: it.Filename, Kind: it.Kind, Pages: pi.Pages, Copies: o.Copies,
			Duplex: o.Duplex, PageRange: pi.PageRange, Sheets: pi.Sheets, State: store.StateQueued,
		}
		if err := s.Store.Create(ctx, &j); err != nil {
			s.Staging.Discard(it)
			return jobs, err
		}
		jobs = append(jobs, j)
		s.queue <- task{job: j, item: it}
	}
	if len(jobs) == 0 {
		return nil, errors.New("these files were already printed")
	}
	return jobs, nil
}

// Run sends queued jobs one at a time and resumes jobs interrupted by a restart.
func (s *Service) Run(ctx context.Context) {
	s.recover(ctx)
	for {
		select {
		case <-ctx.Done():
			return
		case t := <-s.queue:
			s.send(ctx, t)
		}
	}
}

// Init must be called before Submit or Run.
func (s *Service) Init() {
	s.queue = make(chan task, 256)
	if s.PollInterval == 0 {
		s.PollInterval = 3 * time.Second
	}
	if s.PollTimeout == 0 {
		s.PollTimeout = 30 * time.Minute
	}
}

func (s *Service) recover(ctx context.Context) {
	jobs, err := s.Store.Unfinished(ctx)
	if err != nil {
		s.Log.Error("load unfinished jobs", "err", err)
		return
	}
	for _, j := range jobs {
		if j.IPPJobID == 0 {
			// Staged files do not survive a restart, so this can't be sent.
			s.finish(ctx, j, store.StateFailed, "netpr restarted before the job was sent; upload it again")
			continue
		}
		go s.follow(ctx, s.Printer.Get(), j)
	}
}

func (s *Service) send(ctx context.Context, t task) {
	j := t.job
	defer s.Staging.Discard(t.item) // never keep documents after sending
	log := s.Log.With("job", j.ID, "file", j.Filename)
	s.setState(ctx, j.ID, store.StatePreparing, "", 0)

	path := t.item.PDFPath()
	if j.PageRange != "" {
		trimmed := filepath.Join(t.item.Dir, "selected.pdf")
		if err := s.Converter.Split(ctx, path, j.PageRange, trimmed); err != nil {
			log.Error("split", "range", j.PageRange, "err", err)
			s.finish(ctx, j, store.StateFailed, "could not extract pages "+j.PageRange)
			return
		}
		path = trimmed
	}

	pc := s.Printer.Get()
	path, format, err := s.document(ctx, pc, t.item.Dir, path, j.Duplex)
	if err != nil {
		log.Error("rasterize", "err", err)
		s.finish(ctx, j, store.StateFailed, "could not prepare the pages for the printer")
		return
	}
	f, err := os.Open(path)
	if err != nil {
		s.finish(ctx, j, store.StateFailed, err.Error())
		return
	}
	defer f.Close()
	st, err := f.Stat()
	if err != nil {
		s.finish(ctx, j, store.StateFailed, err.Error())
		return
	}

	if s.DryRun {
		log.Info("dry run: not sending to printer", "format", format, "bytes", st.Size())
		s.finish(ctx, j, store.StateDryRun, "dry run: not sent to the printer")
		return
	}

	s.setState(ctx, j.ID, store.StateSending, "", 0)
	opts := printer.PrintOptions{
		JobName: j.Filename, User: j.User, Format: format, Copies: j.Copies, Sides: s.sides(j.Duplex),
	}
	sendCtx, cancel := context.WithTimeout(ctx, 10*time.Minute)
	ippID, err := pc.Print(sendCtx, f, int(st.Size()), opts)
	cancel()
	if err != nil {
		log.Error("print", "err", err)
		s.finish(ctx, j, store.StateFailed, "printer rejected the job: "+err.Error())
		return
	}
	log.Info("sent", "ipp_job", ippID, "printer", pc.URI(), "format", format, "bytes", st.Size(),
		"pages", j.Pages, "copies", j.Copies, "duplex", j.Duplex)
	j.IPPJobID, j.State = ippID, store.StatePending
	s.setState(ctx, j.ID, store.StatePending, "", ippID)
	go s.follow(ctx, pc, j)
}

// document decides what to send: the PDF itself, or the pages rendered as
// PWG Raster for printers that can't print PDF (many AirPrint-only models).
func (s *Service) document(ctx context.Context, pc *printer.Client, dir, pdfPath string, duplex bool) (string, string, error) {
	st := s.Monitor.Status()
	if st.URI != pc.URI() || !st.Reachable {
		st = s.Monitor.Refresh(ctx)
	}
	if !st.Reachable || st.SupportsPDF() || !st.SupportsRaster() {
		// Unreachable fails at send time; a printer with neither format
		// rejects the PDF with its own message.
		return pdfPath, printer.FormatPDF, nil
	}
	if duplex && st.RasterSheetBack != "" && st.RasterSheetBack != "normal" {
		s.Log.Warn("printer wants back sides transformed; double-sided pages may come out upside down",
			"sheet_back", st.RasterSheetBack)
	}
	out := filepath.Join(dir, "document.pwg")
	f, err := os.Create(out)
	if err != nil {
		return "", "", err
	}
	defer f.Close()
	start := time.Now()
	pages, err := raster.Convert(ctx, pdfPath, f, raster.Options{
		DPI: st.RasterDPI(), Media: raster.MediaFor(s.Converter.PaperSize()), Duplex: duplex,
	})
	if err != nil {
		return "", "", err
	}
	if err := f.Close(); err != nil {
		return "", "", err
	}
	s.Log.Info("rendered pages for the printer", "pages", pages, "dpi", st.RasterDPI(),
		"seconds", time.Since(start).Round(10*time.Millisecond).Seconds())
	return out, printer.FormatPWGRaster, nil
}

// sides picks the IPP sides keyword, omitting it when the printer says it
// has no sides support at all.
func (s *Service) sides(duplex bool) string {
	if st := s.Monitor.Status(); st.Reachable && len(st.Sides) == 0 {
		return ""
	}
	if duplex {
		return printer.SidesLongEdge
	}
	return printer.SidesOneSided
}

// follow polls the printer the job was sent to until the job reaches a final
// state, even if the active printer is switched meanwhile.
func (s *Service) follow(ctx context.Context, pc *printer.Client, j store.Job) {
	deadline := time.Now().Add(s.PollTimeout)
	t := time.NewTicker(s.PollInterval)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-t.C:
		}
		if time.Now().After(deadline) {
			s.finish(ctx, j, store.StateUnknown, "stopped tracking: the printer never reported the job as finished")
			return
		}
		pollCtx, cancel := context.WithTimeout(ctx, 15*time.Second)
		js, err := pc.JobStatus(pollCtx, j.IPPJobID)
		cancel()
		if errors.Is(err, printer.ErrJobNotFound) {
			// Small printers forget finished jobs quickly.
			s.finish(ctx, j, store.StateCompleted, "")
			return
		}
		if err != nil {
			s.Log.Warn("job status", "job", j.ID, "err", err)
			continue
		}
		msg := js.Message
		if msg == "none" {
			msg = "" // some printers fill job-state-message with the keyword "none"
		}
		switch js.State {
		case "completed", "canceled", "aborted":
			if js.State == "completed" {
				msg = "" // e.g. "job-completed-successfully"; nothing to add
			}
			s.finish(ctx, j, js.State, msg)
			return
		case "pending", "processing":
			if js.State != j.State {
				j.State = js.State
				s.setState(ctx, j.ID, js.State, msg, 0)
			}
		}
	}
}

// setState records a stage change. A failed write is logged rather than
// returned: the job itself carries on either way.
func (s *Service) setState(ctx context.Context, id int64, state, msg string, ippJobID int) {
	if err := s.Store.UpdateState(ctx, id, state, msg, ippJobID); err != nil {
		s.Log.Error("update job", "job", id, "state", state, "err", err)
	}
}

func (s *Service) finish(ctx context.Context, j store.Job, state, msg string) {
	if err := s.Store.UpdateState(ctx, j.ID, state, msg, 0); err != nil {
		s.Log.Error("update job", "job", j.ID, "err", err)
	}
	s.Metrics.JobFinished(state, j.Pages*j.Copies, j.Sheets)

	var title, body string
	prio := notify.PriorityNormal
	switch state {
	case store.StateCompleted, store.StateDryRun:
		title, prio = "Printed", notify.PriorityQuiet
		body = fmt.Sprintf("%s (%s) for %s", j.Filename, plural(j.Pages*j.Copies, "page"), j.User)
		if state == store.StateDryRun {
			title = "Printed (dry run)"
		}
	default:
		title = "Print job " + state
		body = j.Filename
		if msg != "" {
			body += ": " + msg
		}
	}
	go func() {
		nctx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 20*time.Second)
		defer cancel()
		if err := s.Notifier.Notify(nctx, title, body, prio); err != nil {
			s.Log.Warn("notify", "err", err)
		}
	}()
}

func plural(n int, word string) string {
	if n == 1 {
		return "1 " + word
	}
	return fmt.Sprintf("%d %ss", n, word)
}
